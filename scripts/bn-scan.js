/* বাংলা অক্ষর গোনা — range সবসময় কোডপয়েন্টে, কারণ বাংলা হরফে লিখলে
   ড়/ঢ়/য়-এর ভাঙা রূপে "Range out of order" দিয়ে স্ক্রিপ্টই মরে। */
const BN_G = /[অ-হৎড়-য়]/g;
/*  মন্তব্য বাদ দেওয়া।
 *
 *  ⚠️ আগে কেবল **নিজের লাইনে থাকা** `//` মন্তব্য বাদ পড়ত। কোডের পরে
 *  বসানো মন্তব্য থেকে যেত, আর এই রিপোর মন্তব্য বাংলায় লেখা — ফলে
 *  `list.push(key);  // একই জিনিস দু'বার কিনলে…` থেকে অ্যাপোস্ট্রফি
 *  দুটোর মাঝের অংশটা "স্ট্রিং" হিসেবে ধরা পড়ে অনুবাদ চাইত। মন্তব্য
 *  থেকে ভুয়া চাবি — এই রিপোতে ওয়েবসাইটের extractor-এও ঠিক এটাই একবার
 *  হয়েছিল (পঞ্জিকায় ১৬টা)।
 *
 *  ⚠️ লেজের মন্তব্য কাটা হয় **শর্তসাপেক্ষে**: `//`-এর আগে ফাঁকা থাকতে
 *  হবে, আগের অক্ষর `:` হওয়া চলবে না (`https://`), আর ওই `//`-এর আগে
 *  লাইনটায় উদ্ধৃতি-চিহ্নের সংখ্যা জোড় হতে হবে — অর্থাৎ স্ট্রিংয়ের
 *  ভিতরের `//` কাটা পড়ে না। সন্দেহ হলে কাটা হয় না; বেশি কাটলে সত্যিকারের
 *  লেখা অদৃশ্য হয়ে **মিথ্যে সবুজ** হতো, যা ভুয়া চাবির চেয়ে খারাপ। */
function cutTrailingComment(line) {
  for (let i = 1; i < line.length - 1; i++) {
    if (line[i] !== '/' || line[i + 1] !== '/') continue;
    if (!/\s/.test(line[i - 1])) continue;
    if (line[i - 1] === ':') continue;   // https:// — ফাঁকার নিয়মেও ধরা পড়ে, তবু স্পষ্ট থাক
    const head = line.slice(0, i);
    const q = (head.match(/(^|[^\\])['"`]/g) || []).length;
    if (q % 2 !== 0) continue;
    return head;
  }
  return line;
}

const strip = s => s
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .replace(/^[ \t]*\/\/.*$/gm, '')
  .split('\n').map(cutTrailingComment).join('\n');
module.exports = { BN_G, strip, count: s => (s.match(BN_G) || []).length };
